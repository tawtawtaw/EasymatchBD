export function fillMessageTemplate(
  template: string,
  values: Record<string, string | number>,
) {
  return Object.entries(values).reduce(
    (text, [key, value]) => text.replace(new RegExp(`\\{${key}\\}`, "g"), String(value)),
    template,
  );
}

export function formatRelationshipStatus(
  locale: AppLocale,
  status: "none" | "self" | "interest_sent" | "interest_received" | "connected",
) {
  if (status === "none" || status === "self") {
    return "";
  }
  return navigation[locale].relationship[status];
}
